#!/usr/bin/env python3
"""The fraud scoring API of the health insurance sample: POST a claim, get its score, risk level and three reasons.

Standard library only, so it runs as a Cloudera AI Application (or anywhere) without installing anything:

    python samples/health_insurance/scoring/service.py            # listens on CDSW_APP_PORT, else PORT, else 8090

On start it reads the historical claims (data/, generated by generate_data.py) so a new claim is compared with everything before it:
the same bank account, the same doctor on the same day, the same visit at another provider. Each scored claim is then remembered, so
a stream of claims builds on itself. A restart starts again from the history.

Endpoints
  GET  /health   model version and how many claims it knows
  POST /score    one claim (the columns of hi_klaim) or {"claims": [...]}; returns, per claim, skor_fraud, tingkat_risiko,
                 alasan, versi_model, and an "alert" row ready to append to hi_alert when the score reaches the alert threshold

Set SCORING_API_KEY to require "Authorization: Bearer <key>". The model is an example trained on synthetic data.
"""
from __future__ import annotations

import json
import os
import sys
import threading
import time
from datetime import datetime, timedelta, timezone
from http.server import BaseHTTPRequestHandler, ThreadingHTTPServer
from pathlib import Path

try:
    HERE = Path(__file__).resolve().parent
except NameError:  # a Cloudera AI Application script runs in a kernel, where __file__ is not defined: the project root is the working directory
    HERE = Path(os.environ.get("HI_SCORING_DIR") or Path.cwd() / "samples" / "health_insurance" / "scoring").resolve()
sys.path.insert(0, str(HERE))

from model import Model, arrival_order, new_context, read  # noqa: E402

REQUIRED = ("id_klaim", "id_peserta", "kode_penyedia", "kode_dokter", "tanggal_masuk", "tanggal_keluar", "tanggal_pengajuan",
            "jenis_layanan", "kode_diagnosis", "jumlah_tagihan_idr")
WIB = timezone(timedelta(hours=7))


class Scorer:
    """The model and what it knows; one lock, because each claim changes what the next one is compared with."""

    def __init__(self) -> None:
        started = time.monotonic()
        self.model = Model.load()
        self.context = new_context(self.model.spec)
        self.seen: dict[str, dict] = {}
        self.lock = threading.Lock()
        for claim in arrival_order(read("klaim.csv")):
            self.context.remember(claim)
            self.seen[claim["id_klaim"]] = {}
        print(f"scoring service: model {self.model.version}, {len(self.seen):,} historical claims read in "
              f"{time.monotonic() - started:.1f}s", flush=True)

    def score(self, claim: dict) -> dict:
        missing = [f for f in REQUIRED if not str(claim.get(f) or "").strip()]
        if missing:
            raise ValueError(f"claim {claim.get('id_klaim') or '?'} is missing: {', '.join(missing)}")
        claim = {**claim, "jumlah_tagihan_idr": str(claim["jumlah_tagihan_idr"]), "lama_rawat_hari": str(claim.get("lama_rawat_hari") or 0)}
        with self.lock:
            if claim["id_klaim"] in self.seen and self.seen[claim["id_klaim"]]:
                return self.seen[claim["id_klaim"]]  # scored before: the same answer, the claim is not counted twice
            values, facts = self.context.features(claim)
            result = self.model.score(values, facts)
            if claim["id_klaim"] not in self.seen:
                self.context.remember(claim)
            out = {"id_klaim": claim["id_klaim"], **result, "alert": None}
            if result["skor_fraud"] >= self.model.alert_at:
                reasons = result["alasan"] + ["", "", ""]
                out["alert"] = {
                    "id_alert": "ALR-" + claim["id_klaim"].removeprefix("KLM-"), "id_klaim": claim["id_klaim"],
                    "waktu_alert": datetime.now(WIB).strftime("%Y-%m-%d %H:%M:%S.000"), "skor_fraud": result["skor_fraud"],
                    "tingkat_risiko": result["tingkat_risiko"], "alasan_1": reasons[0], "alasan_2": reasons[1], "alasan_3": reasons[2],
                    "versi_model": result["versi_model"],
                }
            self.seen[claim["id_klaim"]] = out
            return out


def handler_for(scorer: Scorer, api_key: str):
    class Handler(BaseHTTPRequestHandler):
        def _send(self, status: int, body: dict) -> None:
            data = json.dumps(body, ensure_ascii=False).encode()
            self.send_response(status)
            self.send_header("Content-Type", "application/json; charset=utf-8")
            self.send_header("Content-Length", str(len(data)))
            self.end_headers()
            self.wfile.write(data)

        def _authorised(self) -> bool:
            if not api_key or self.headers.get("Authorization", "") == f"Bearer {api_key}":
                return True
            self._send(401, {"error": "missing or wrong Authorization: Bearer <SCORING_API_KEY>"})
            return False

        def do_GET(self) -> None:  # noqa: N802
            if self.path.rstrip("/") in ("", "/health"):
                self._send(200, {"status": "ok", "versi_model": scorer.model.version, "klaim_diketahui": len(scorer.seen),
                                 "ambang": {"alert": scorer.model.alert_at, "tinggi": scorer.model.high_at}})
            else:
                self._send(404, {"error": "not found"})

        def do_POST(self) -> None:  # noqa: N802
            if self.path.rstrip("/") != "/score":
                self._send(404, {"error": "not found"})
                return
            if not self._authorised():
                return
            try:
                body = json.loads(self.rfile.read(int(self.headers.get("Content-Length") or 0)) or b"{}")
                claims = body.get("claims") if isinstance(body, dict) and "claims" in body else [body]
                if not isinstance(claims, list) or not claims or len(claims) > 1000:
                    raise ValueError("send one claim, or {\"claims\": [...]} with 1 to 1000 claims")
                results = [scorer.score(c) for c in claims]
            except (ValueError, KeyError, TypeError, json.JSONDecodeError) as exc:
                self._send(400, {"error": str(exc)})
                return
            self._send(200, results[0] if len(results) == 1 and "claims" not in body else {"results": results})

        def log_message(self, fmt: str, *args) -> None:
            pass  # one line per request would drown the Application log

    return Handler


def main() -> int:
    port = int(os.environ.get("CDSW_APP_PORT") or os.environ.get("PORT") or 8090)
    scorer = Scorer()
    server = ThreadingHTTPServer(("127.0.0.1" if os.environ.get("CDSW_APP_PORT") else "0.0.0.0", port), handler_for(scorer, os.environ.get("SCORING_API_KEY", "")))
    print(f"scoring service listening on port {port}", flush=True)
    server.serve_forever()
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
